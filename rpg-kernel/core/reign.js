// 同年号多朝重复（如「建兴」有三国/西晋/东吴多个）—— 取最早一个作为兜底，
// 真正的判定应结合 polity（政权）。这里给出全部候选，供上层按政权筛选。
function candidatesOf(name) {
  return REIGNS.filter(r => r[0] === name).map(r => r[1]);
}

const CN = { 元: 1, 正: 1, 一: 1, 二: 2, 三: 3, 四: 4, 五: 5, 六: 6, 七: 7, 八: 8, 九: 9, 十: 10 };
function parseYearNum(s) {
  s = String(s || '').trim();
  if (/^\d{1,3}$/.test(s)) return Number(s);
  if (s === '元' || s === '元年') return 1;
  if (s.includes('十')) {
    const [a, b] = s.split('十');
    const hi = a ? (CN[a] || 0) : 1;
    const lo = b ? (CN[b] || 0) : 0;
    return hi * 10 + lo || null;
  }
  return CN[s] || null;
}

const NUM = '([0-9]{1,3}|[元一二三四五六七八九十]{1,4})';

/**
 * 把「大业十一年」「熙宁元年」「615年」之类换算成公元年。
 * @returns {year:number|null, reign:string|null, n:number|null, fromReign:boolean, note:string}
 */
function resolveGregorian(label, polity) {
  const t = String(label || '').trim();
  if (!t) return { year: null, reign: null, n: null, note: '年号为空' };

  // ① 直接给了公元年
  let m = t.match(/(-?\d{1,4})\s*年/);
  if (m && Math.abs(Number(m[1])) > 100) {
    return { year: Number(m[1]), reign: null, n: null, fromReign: false, note: '直接给出公元年' };
  }

  // ② 年号 + 年数
  //    先在原文里定位年号（长名优先：太平兴国 > 太平），再**从年号之后**解析年数。
  //    不能用一个笼统的「2~4 汉字 + 数字」正则 —— 中文数字本身也是汉字，
  //    会把「大业十一年」切成「大业十」+「一」，算成 1 年。
  const names = REIGNS.map(r => r[0]);
  let best = null, bestPos = -1;
  for (const cand of names) {
    const p = t.indexOf(cand);
    if (p >= 0 && (!best || cand.length > best.length || (cand.length === best.length && p < bestPos))) { best = cand; bestPos = p; }
  }
  if (best) {
    const name = best;
    const rest = t.slice(bestPos + best.length);
    const rm = rest.match(new RegExp(`^\\s*${NUM}\\s*[年载]`)) || rest.match(/^\s*(元)/);
    let n = 1;
    if (rm && rm[1]) n = /^\d+$/.test(rm[1]) ? Number(rm[1]) : parseYearNum(rm[1]);
    const cands = candidatesOf(name);
    if (cands.length) {
      const starts = cands.slice();
      // 政权提示：若给了政权（如「隋」），优先落在该政权常见范围内的起年
      let start = starts[0];
      if (polity) {
        const p = String(polity);
        const hint = starts.find(s => p.includes('隋') ? (s >= 581 && s <= 620)
          : p.includes('唐') ? (s >= 618 && s <= 910)
            : p.includes('宋') ? (s >= 960 && s <= 1280)
              : p.includes('明') ? (s >= 1368 && s <= 1650)
                : p.includes('清') ? (s >= 1600 && s <= 1912)
                  : p.includes('汉') ? (s >= -210 && s <= 230)
                    : p.includes('晋') ? (s >= 260 && s <= 430) : true);
        if (hint != null) start = hint;
      }
      const year = start + n - 1;
      return {
        year, reign: name, n, fromReign: true,
        note: `${name}元年为 ${start} 年，${name}${n}年 → ${year} 年`,
      };
    }
    return { year: null, reign: name, n, note: `年号「${name}」不在本地年号表中` };
  }

  // ③ 只有年号没有年数（前面 ② 已算出 best）：按元年处理
  if (best) {
    const cands = candidatesOf(best);
    return { year: cands[cands.length - 1], reign: best, n: 1, fromReign: true, note: `只给了年号，按元年处理（${cands[cands.length - 1]} 年）` };
  }
  return { year: null, reign: null, n: null, note: '无法从年号中解析出公元年' };
}

/* 从 Wikidata 的 xsd:dateTime 字符串里取年份。
   坑：公元前的日期是 "-0208-01-01T00:00:00Z"，用 slice(0,4) 会得到 "-020" → -20，
   于是「李斯卒于公元前 208 年」被读成「卒于公元前 20 年」，整个世界错代。
   必须按「开头的可选负号 + 1~4 位数字」整体取。 */
function yearOf(v) {
  if (v == null) return null;
  const m = String(v).match(/^\s*(-?\d{1,4})/);
  if (!m) return null;
  const n = Number(m[1]);
  return Number.isFinite(n) ? n : null;
}

module.exports = { resolveGregorian, REIGNS, candidatesOf, parseYearNum, yearOf };
