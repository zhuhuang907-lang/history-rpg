/* 供审查/扫描用：按词长倒序，先长后短，避免「经济政策」被「经济」截断 */
const SORTED = [...MAP].sort((a, b) => b.m.length - a.m.length);
const indexable = SORTED.map(x => ({ re: new RegExp(escapeRe(x.m), 'g'), ...x }));
function escapeRe(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }

/** 扫描文本里的现代词，返回去重后的命中（含古代对应说法）。
    会同时扫描「原文」与「去掉口语虚字后的文本」，以接住「开个会」「用一下手机」这类口语。 */
function scanModern(text) {
  const t = String(text || '');
  if (!t) return [];
  const stripped = t.replace(/[个了下着过地得]|一下|一会儿|一下子/g, '');
  const hay = stripped !== t ? [t, stripped] : [t];
  const hits = [];
  const seen = new Set();
  for (const x of indexable) {
    if (seen.has(x.m)) continue;
    let hit = false;
    for (const h of hay) { if (x.re.test(h)) { hit = true; x.re.lastIndex = 0; break; } x.re.lastIndex = 0; }
    if (hit) { seen.add(x.m); hits.push({ modern: x.m, ancient: x.a, cat: x.cat }); }
  }
  return hits;
}

/** 给 GM 的「现代词汇转译」段：把玩家的现代说法落到古代行为上 */
function renderTranslation(input) {
  const hits = scanModern(input);
  if (!hits.length) return '';
  return [
    '=== 玩家用了现代词汇 / 现代做法 —— 必须转译，不得直接搬进古代场景 ===',
    '玩家本回合的原话里含下列现代说法。你要做的是**把他的意思落成那个时代真实可行的做法与说法**，然后照此演；绝对不要在正文里出现这些现代词，也不要让剧情里冒出对应的现代制度、现代观念或现代器物。',
    hits.map(h => `· 「${h.modern}」（${h.cat}）→ 应作：${h.ancient}`).join('\n'),
    '另外：understood 字段复述玩家意图时，也须改用当时的话，不要保留现代词。',
  ].join('\n');
}

/** 审查用：正文里若冒出这些词，即为穿帮 */
function modernHitsIn(scene) { return scanModern(scene); }

const listModern = () => SORTED.map(({ m, a, cat }) => ({ modern: m, ancient: a, cat }));

module.exports = { scanModern, renderTranslation, modernHitsIn, listModern, MAP };
